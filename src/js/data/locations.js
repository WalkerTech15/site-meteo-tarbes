/* Accent/case-insensitive normalization for search */
export function normalize(str) {
  return str.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").trim();
}

export function findLocations(query, lang) {
  const q = normalize(query);
  if (!q) return [];
  const scored = [];
  for (const loc of LOCATIONS) {
    const names = [loc.name.en, loc.name.fr, ...loc.aliases].map(normalize);
    let score = -1;
    for (const n of names) {
      if (n === q) {
        score = 100;
        break;
      }
      if (n.startsWith(q)) score = Math.max(score, 60 + (q.length / n.length) * 20);
      else if (n.includes(q) && q.length >= 3) score = Math.max(score, 30);
    }
    if (score >= 0) scored.push({ loc, score });
  }
  scored.sort((a, b) => b.score - a.score || a.loc.name[lang].localeCompare(b.loc.name[lang]));
  return scored.slice(0, 7).map((s) => s.loc);
}
